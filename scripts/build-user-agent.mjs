// Writes nodes/Shotstack/userAgent.ts from the version in package.json.
//
//   node scripts/build-user-agent.mjs
//
// `npm run build` runs this first, so the published package always carries the
// version it was built at. A hand-written literal drifts on the next release,
// and then every render in raw.renders.user_agent reports the wrong version.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
const target = 'nodes/Shotstack/userAgent.ts';

const contents = `/**
 * Names this node, and its version, in Shotstack's render log.
 *
 * Every request must send it. n8n replaces a missing User-Agent with a bare
 * "n8n", which is what a plain HTTP Request node sends, so the render becomes
 * uncountable.
 *
 * GENERATED by scripts/build-user-agent.mjs. Do not edit.
 */
export const USER_AGENT = 'shotstack-n8n-node/${version}';
`;

const existing = (() => {
	try {
		return readFileSync(target, 'utf8');
	} catch {
		return '';
	}
})();

if (existing === contents) {
	console.log(`userAgent.ts already at ${version}`);
} else {
	writeFileSync(target, contents);
	console.log(`userAgent.ts written at ${version}`);
}
